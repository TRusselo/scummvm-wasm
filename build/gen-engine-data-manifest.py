#!/usr/bin/env python3
"""Generate the engine-data manifest compiled into the core.

The manifest lets LibretroRemoteDirectory answer hasFile() and listMembers()
without touching the network, so ScummVM's detection and search-set walks never
block on a round trip. Only createReadStreamForMember() fetches.

Kept in step with build-retroarch-core.sh's rsync by sharing its exclusions:
anything that script declines to stage is not published and so must not appear
here either.
"""
import sys
from pathlib import Path

EXCLUDE_DIRS = {"patches", "fonts", "testbed-audiocd-files"}
EXCLUDE_NAMES = {
    "README", "engine_data.mk", "engine_data_core.mk", "engine_data_big.mk",
    "create-playground3d-data.sh", "create-testbed-data.sh",
}


def collect(src: Path):
    out = []
    for p in sorted(src.iterdir()):
        if p.is_dir() or p.name in EXCLUDE_NAMES or p.name in EXCLUDE_DIRS:
            continue
        out.append((p.name, p.stat().st_size))
    return out


def main():
    src, dest = Path(sys.argv[1]), Path(sys.argv[2])
    entries = collect(src)
    if not entries:
        sys.exit(f"error: no engine-data files found under {src}")

    lines = [
        "// Generated by build/gen-engine-data-manifest.py. Do not edit.",
        "",
        "#ifndef BACKENDS_PLATFORM_LIBRETRO_ENGINE_DATA_MANIFEST_H",
        "#define BACKENDS_PLATFORM_LIBRETRO_ENGINE_DATA_MANIFEST_H",
        "",
        "struct LibretroEngineDataEntry {",
        "\tconst char *name;",
        "\tunsigned int size;",
        "};",
        "",
        "static const LibretroEngineDataEntry s_engineDataManifest[] = {",
    ]
    for name, size in entries:
        lines.append('\t{ "%s", %du },' % (name, size))
    lines += [
        "};",
        "",
        "static const unsigned int s_engineDataManifestCount = %du;" % len(entries),
        "",
        "#endif",
        "",
    ]
    dest.write_text("\n".join(lines))
    total = sum(s for _, s in entries)
    print(f"engine-data manifest: {len(entries)} files, {total} bytes -> {dest}")


if __name__ == "__main__":
    main()
